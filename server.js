const express = require('express');
const app = express();
app.use(express.json({limit:'100mb'}));
let master={},green=[];
app.get('/',(q,r)=>r.send('ok <a href="/m">/m</a>'));
app.get('/m',(q,r)=>r.send('m is working - <a href="/stats">stats</a> - <a href="/admin">admin</a>'));
app.get('/admin',(q,r)=>r.send('admin ok - <a href="/stats">stats</a>'));
app.get('/stats',(q,r)=>r.json({master:Object.keys(master).length,green:green.length}));
app.post('/add',(q,r)=>{let v=(q.body.voter||'').toString().replace(/\D/g,'');if(!v)return r.json({ok:false});green.push({voter:v});r.json({ok:true})});
app.post('/upload-master',(q,r)=>{let c=0;(q.body.text||'').split('\n').forEach(l=>{let p=l.split(',');let v=(p[0]||'').replace(/\D/g,'').trim();if(v.length>4){master[v]={voter:v,name:(p[1]||'').trim()};c++}});r.json({ok:true,count:Object.keys(master).length,added:c})});
app.get('/clear-green',(q,r)=>{green=[];r.json({ok:true})});
app.listen(process.env.PORT||8080,'0.0.0.0',()=>console.log('up'));
